<?php
/**
 * Generates SQL to seed development users with real bcrypt password hashes.
 *
 * Usage:
 *   php database/make_seed_users.php > database/seed_users.sql
 *
 * WARNING: Development credentials only. All accounts have must_change_pw = 1.
 * Replace these temporary passwords immediately via the API change-password
 * flow or an admin password reset before any shared/real deployment.
 */

declare(strict_types=1);

$users = [
    // username, full name, email, role code, TEMP password
    ['admin',    'System Administrator', 'admin@epeddlers.local',    'admin',             'Admin@123'],
    ['treasury', 'Treasury Officer',     'treasury@epeddlers.local', 'treasury',          'Treasury@123'],
    ['inspector','Inspection Officer',   'inspector@epeddlers.local','inspection_officer','Inspect@123'],
    ['sanitary', 'Sanitary Officer',     'sanitary@epeddlers.local', 'sanitary_officer',  'Sanitary@123'],
];

echo "-- Generated by make_seed_users.php. Development credentials only.\n";
echo "-- All passwords are temporary; must_change_pw = 1.\n";
echo "SET NAMES utf8mb4;\n\n";

foreach ($users as [$username, $name, $email, $roleCode, $password]) {
    $hash = password_hash($password, PASSWORD_BCRYPT);
    $u = fn($s) => str_replace("'", "''", $s);

    echo "INSERT INTO users (full_name, email, username, password_hash, status, must_change_pw)\n";
    echo "VALUES ('{$u($name)}', '{$u($email)}', '{$u($username)}', '{$u($hash)}', 'active', 1)\n";
    echo "ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), full_name = VALUES(full_name);\n\n";

    echo "INSERT IGNORE INTO user_roles (user_id, role_id)\n";
    echo "SELECT u.id, r.id FROM users u JOIN roles r\n";
    echo "WHERE u.username = '{$u($username)}' AND r.code = '{$u($roleCode)}';\n\n";
}

echo "-- Temporary credentials (CHANGE IMMEDIATELY):\n";
foreach ($users as [$username, , , $roleCode, $password]) {
    echo "--   {$username} / {$password}   (role: {$roleCode})\n";
}
